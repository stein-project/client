fn main() {
    // The icon is embedded in the .exe at build time; without these, changing the icon does not rebuild the resource
    // and the .exe ships with the old icon.
    println!("cargo:rerun-if-changed=icons");
    println!("cargo:rerun-if-changed=tauri.conf.json");
    tauri_build::build()
}
