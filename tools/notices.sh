# Regenerates THIRD-PARTY-NOTICES.txt: the full licence texts of the open source software inside SteinClient.exe.
#
#   - the Rust crates linked into the launcher on Windows, through cargo-about (about.toml, tools/notices.hbs);
#   - the npm packages bundled into the interface (NPM_PACKAGES below), with the licence files from ui/node_modules.
#
# Needs cargo-about (cargo install cargo-about --locked --features cli) and `npm ci` already run in ui/. Run it again
# whenever Cargo.lock or ui/package-lock.json changes, and commit the result.
#
#   tools/notices.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
OUT=THIRD-PARTY-NOTICES.txt
# What Vite bundles into ui/dist: the dependencies in ui/package.json plus scheduler (react-dom's). Build-time tools
# (TypeScript, Vite, loose-envify) are not shipped.
NPM_PACKAGES=(react react-dom scheduler @tauri-apps/api @fontsource/cinzel @fontsource/eb-garamond @fontsource/jetbrains-mono)

[ -d ui/node_modules ] || { echo "run npm ci in ui/ first" >&2; exit 1; }
rust="$(mktemp)"; trap 'rm -f "$rust"' EXIT
cargo about generate --locked --fail -c about.toml -m launcher/Cargo.toml tools/notices.hbs -o "$rust"

{
  cat <<'TXT'
Stein Client: third-party software notices
==========================================

SteinClient.exe contains the open source software listed below. Each component is used under its own licence, whose
full text follows. The Stein Client itself is licensed under the Mozilla Public License 2.0 (LICENSE).

This file is generated by tools/notices.sh: do not edit it by hand.

TXT
  tr -d '\r' < "$rust"
  printf '\nnpm packages (the interface)\n============================\n\n'
  for p in "${NPM_PACKAGES[@]}"; do
    dir="ui/node_modules/$p"
    version="$(sed -n 's/^  "version": "\(.*\)",*$/\1/p' "$dir/package.json" | head -1)"
    license="$(sed -n 's/^  "license": "\(.*\)",*$/\1/p' "$dir/package.json" | head -1)"
    files=("$dir"/LICENSE*)
    [ -e "${files[0]}" ] || { echo "no licence file in $dir" >&2; exit 1; }
    printf -- '-------------------------------------------------------------------------------\n'
    printf '%s %s (%s)\n\n' "$p" "$version" "$license"
    for f in "${files[@]}"; do
      case "$f" in *.spdx) continue ;; esac
      tr -d '\r' < "$f"
      printf '\n'
    done
  done
} > "$OUT"
echo "$OUT: $(wc -l < "$OUT") lines"
